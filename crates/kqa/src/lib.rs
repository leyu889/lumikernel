//! `kqa` —— 质量工程（M11）
//!
//! 四个模块，全部是**纯逻辑**：不碰硬件、不分配内存、不依赖任何其他 crate。
//! 这样它们能在宿主机上跑单测，也能被内核在分配失败路径里安全调用
//! （故障注入的判定函数本身绝不能分配内存，否则会自己触发自己）。
//!
//! - [`rng`]：确定性随机数。**同一个种子必须给出同一串数**——否则
//!   "复现一次失败"就成了一门玄学，fuzz 出来的问题也就没法定位。
//! - [`fault`]：故障注入的判定策略。把"第几次失败"这件事从硬件里拿出来，
//!   变成可测试的纯状态机。
//! - [`soak`]：长跑采样与线性回归。用整数最小二乘算斜率，不用浮点
//!   （内核里没有 FPU 上下文，浮点会污染用户态的 SSE 状态）。
//! - [`fuzz`]：非法输入生成。以"有意思的值"为主、随机值为辅——
//!   纯随机 64 位整数几乎永远命不中边界。
#![no_std]
#![deny(unsafe_code)]

pub mod fault;
pub mod fuzz;
pub mod rng;
pub mod soak;

// 宿主机跑单测时，测试框架本身需要 std（内核构建里这一行不参与）。
#[cfg(test)]
extern crate std;
